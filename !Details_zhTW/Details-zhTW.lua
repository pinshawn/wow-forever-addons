-- 2. 之後再登記的 Details! 繁中：寫進來的字丟掉
local origNewLocale = AL.NewLocale
local sink = setmetatable({}, { __newindex = function() end, __index = function() return nil end })
AL.NewLocale = function(self, application, locale, isDefault, silent)
	if application == "Details" and locale == "zhTW" and not isDefault then
		origNewLocale(self, application, locale, isDefault, silent)
		return sink
	end
	return origNewLocale(self, application, locale, isDefault, silent)
end

